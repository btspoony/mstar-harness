/**
 * The browser-side projection of the one disposition vocabulary.
 *
 * `packages/ui` may not import the engine *by value* in its published surface:
 * the engine pulls SQLite and a Node runtime into every host bundle
 * (`src/purity.test.ts`). Both hosts still have to offer exactly the
 * dispositions the store accepts, so this producer runs in Bun during a host
 * build, reads the authoritative tuples from `engine/src/issue.ts`, and emits
 * the browser-safe module the UI (and through it the CLI dashboard and the dsh
 * panel) imports. The engine enters a build script's graph, never a bundle's.
 *
 * The emitted file is a projection, never a second owner: it is regenerated
 * from the tuple, so no test pins its bytes — a stale copy is a build-order
 * fact, and `check:stale` owns that question.
 *
 * Determinism: the output depends on the tuples alone; running twice on
 * unchanged input writes byte-identical text.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ISSUE_DISPOSITIONS, TERMINAL_DISPOSITIONS } from "../../engine/src/issue.js";

const OUT_PATH = path.resolve(import.meta.dir, "..", "src", "issue-vocabulary.generated.ts");

/** One tuple as its TypeScript literal, in declaration order. */
function tuple(values: readonly string[]): string {
  return `[${values.map((value) => JSON.stringify(value)).join(", ")}] as const`;
}

/** The whole generated module. A pure function of the engine tuples. */
export function renderIssueVocabulary(
  dispositions: readonly string[] = ISSUE_DISPOSITIONS,
  terminal: readonly string[] = TERMINAL_DISPOSITIONS,
): string {
  return `/**
 * GENERATED by \`packages/ui/scripts/generate-issue-vocabulary.ts\` from the
 * authoritative tuples in \`packages/engine/src/issue.ts\`. Do not edit: the
 * producer is the only writer, and the UI cannot import the engine by value.
 */

/** Every disposition the store accepts, \`open\` first. */
export const ISSUE_DISPOSITION_VALUES = ${tuple(dispositions)};

/** The terminal subset; \`obsolete\` retires a removed subject, it does not resolve it. */
export const TERMINAL_DISPOSITION_VALUES = ${tuple(terminal)};
`;
}

/** Write the generated module when it differs. Returns the path written. */
export function generateIssueVocabulary(outPath: string = OUT_PATH): string {
  const rendered = renderIssueVocabulary();
  let current: string | null = null;
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    current = null;
  }
  if (current !== rendered) writeFileSync(outPath, rendered);
  return outPath;
}

if (import.meta.main) generateIssueVocabulary();
